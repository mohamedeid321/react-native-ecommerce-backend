import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import mongoose from "mongoose";
import {randomBytes} from "node:crypto";
import Product from "../src/models/product.model.js";
import User from "../src/models/user.model.js";
import Category from "../src/models/category.model.js";
import products from "../src/routes/productRoutes.js";
import categories from "../src/routes/categoryRoutes.js";
import {getRedis} from "../src/lib/redis.js";
import {createSessionStore} from "../src/lib/sessionStore.js";
import {signAccessToken} from "../src/utils/sessionTokens.js";
test("catalog HTTP integration",{skip:!process.env.TEST_MONGO_URI||!process.env.TEST_REDIS_URL,timeout:60000},async()=>{
 process.env.REDIS_URL=process.env.TEST_REDIS_URL;
 process.env.JWT_ACCESS_SECRET=randomBytes(32).toString("hex");
 await mongoose.connect(process.env.TEST_MONGO_URI,{dbName:"lotta_catalog_test_"+randomBytes(8).toString("hex")});
 await Promise.all([User.init(),Product.init(),Category.init()]);
 const app=express();app.use(express.json());app.use("/products",products);app.use("/categories",categories);
 const server=app.listen(0);await new Promise(r=>server.once("listening",r));
 const base="http://127.0.0.1:"+server.address().port;
 const call=(path,method="GET",body,cookie="")=>fetch(base+path,{method,headers:{"Content-Type":"application/json",Cookie:cookie},body:body===undefined?undefined:JSON.stringify(body)});
 try{
 const store=createSessionStore(getRedis());
 const user=await User.create({username:"Catalog customer",email:"catalog@example.com",password:"Test-password-123"});
 const admin=await User.create({username:"Catalog admin",email:"catalog-admin@example.com",password:"Test-password-123",role:"admin"});
 const cookie=async(u,mfa)=>{const s=await store.create(u.id,mfa);return "lotta_access="+signAccessToken(u.id,s.sessionId);};
 const customerCookie=await cookie(user,false),adminCookie=await cookie(admin,true);
 const apple=await Product.create({name:"Apple",description:"Fresh",price:55,discount:10,purchasePrice:44,stock:2.5,category:"fruits",image:"https://example.com/apple.png"});
 const orange=await Product.create({name:"Orange",description:"Fresh",price:20,stock:10,category:"fruits",image:"https://example.com/orange.png"});
 const hidden=await Product.create({name:"Hidden",description:"Fresh",price:10,stock:5,category:"fruits",image:"https://example.com/hidden.png",isActive:false});
 const list=await (await call("/products?sort=price_asc")).json();
 assert.equal(list.totalProducts,2);assert.equal(list.products[0]._id,orange.id||String(orange._id));
 assert.equal(list.products[1].finalPrice,49.5);assert.equal(list.products[1].stock,2.5);assert.equal("purchasePrice" in list.products[1],false);
 assert.equal((await call("/products/"+hidden._id)).status,404);
 assert.equal((await call("/products/admin")).status,401);
 assert.equal((await call("/products/admin","GET",undefined,customerCookie)).status,403);
 const inventory=await (await call("/products/admin","GET",undefined,adminCookie)).json();
 assert.equal(inventory.totalProducts,3);assert.equal(inventory.products.find(p=>p._id===String(apple._id)).purchasePrice,44);
 assert.equal((await call("/products/"+apple._id+"/visibility","PATCH",{isActive:false},customerCookie)).status,403);
 assert.equal((await call("/products/"+apple._id+"/visibility","PATCH",{isActive:false},adminCookie)).status,200);
 assert.equal((await call("/products/"+apple._id)).status,404);
 assert.equal((await call("/products/"+apple._id+"/visibility","PATCH",{isActive:true},adminCookie)).status,200);
 assert.equal((await call("/products/"+apple._id)).status,200);
 assert.equal((await call("/products/"+apple._id,"DELETE",undefined,adminCookie)).status,200);
 assert.ok(await Product.findById(apple._id));assert.equal((await call("/products/"+apple._id)).status,404);
 assert.equal((await call("/categories/tropical","PUT",{name:"Tropical",isActive:true},customerCookie)).status,403);
 assert.equal((await call("/categories/tropical","PUT",{name:"Tropical",isActive:true},adminCookie)).status,200);
 assert.ok((await (await call("/categories")).json()).categories.some(c=>c.slug==="tropical"));
 assert.equal((await call("/categories/tropical","PUT",{name:"Tropical",isActive:false},adminCookie)).status,200);
 assert.ok(!(await (await call("/categories")).json()).categories.some(c=>c.slug==="tropical"));
 }finally{await new Promise(r=>server.close(r));await mongoose.connection.dropDatabase();await mongoose.disconnect();await getRedis().quit();}
});
